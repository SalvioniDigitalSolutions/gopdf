func meanGray(m image.Image, box image.Rectangle) int {
	sum, n := 0, 0
	for y := box.Min.Y; y < box.Max.Y; y++ {
		for x := box.Min.X; x < box.Max.X; x++ {
			sum += int(color.GrayModel.Convert(m.At(x, y)).(color.Gray).Y)
			n++
		}
	}
	return sum / n
}

// A four-colour JPEG in a PDF is taken as stored, then through its
// /Decode, as Poppler and Acrobat take it: Adobe's inverted samples with no
// /Decode show as full ink, and with /Decode [1 0 1 0 1 0 1 0] as the
// picture they hold. Taken as Go's JPEG decoder gives it (Adobe's inversion
// undone, as a viewer of a JPEG file does), every such picture in a PDF
// read the other way round: a report's logo, black on white to every
// viewer, came out all black, and the marked name in it was read by no
// recogniser.
func TestCMYKJPEGIsTakenAsStoredThroughItsDecode(t *testing.T) {
	half := image.Rect(0, 0, 16, 16)
	other := image.Rect(16, 0, 32, 16)
	for _, c := range []struct {
		name, decode string
		left, right  [2]int // mean gray between
	}{
		{"as stored", "", [2]int{0, 40}, [2]int{0, 40}},
		{"through /Decode [1 0 ...]", "/Decode [1 0 1 0 1 0 1 0] ", [2]int{215, 255}, [2]int{0, 40}},
	} {
		pdf := rawImagePage(t, adobeCMYKJPEG, "/Width 32 /Height 16 /ColorSpace /DeviceCMYK /BitsPerComponent 8 "+c.decode+"/Filter /DCTDecode",
			"q 32 0 0 16 100 100 cm /Im0 Do Q")
		m, err := edgeTileImage(t, pdf).Decode()
		if err != nil {
			t.Fatal(err)
		}
		if g := meanGray(m, half); g < c.left[0] || g > c.left[1] {
			t.Errorf("%s: the left half reads %d, want %d..%d", c.name, g, c.left[0], c.left[1])
		}
		if g := meanGray(m, other); g < c.right[0] || g > c.right[1] {
			t.Errorf("%s: the right half reads %d, want %d..%d", c.name, g, c.right[0], c.right[1])
		}
	}
}
